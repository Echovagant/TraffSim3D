"""The discrete forward-pass contract — the Python side.

For the **same weights** and the **same observations**, the Python forward
pass and the TypeScript forward pass must produce the **same action
index**. That is the gate a traffic-signal agent's browser inference
depends on: a policy trained in Python has to pick the same action in the
browser.

The fixture is generated by `scripts/gen_discrete_policy_fixture.py` (the
backend owns the training side) and committed; the frontend's
`src/infrastructure/rl/mlpInference.discrete.spec.ts` asserts the
TypeScript half. This module asserts the Python half: the pure-Python
reference forward pass, run on the committed weights, reproduces the
committed actions.

The fixture lives in the **frontend** folder (like the MLP
fixture) because the frontend is the side that imports it. When the
frontend folder is not checked out, the test skips instead of failing.
"""

from __future__ import annotations

import importlib.util
import json
from pathlib import Path
from types import ModuleType
from typing import Any

import pytest

BACKEND_ROOT = Path(__file__).resolve().parents[1]
REPO_ROOT = BACKEND_ROOT.parent
SCRIPT_PATH = BACKEND_ROOT / "scripts" / "gen_discrete_policy_fixture.py"
FIXTURE_PATH = (
    REPO_ROOT
    / "TraffSim3D-frontend"
    / "src"
    / "infrastructure"
    / "rl"
    / "fixtures"
    / "discrete-policy-fixture.json"
)


def _load_reference() -> ModuleType:
    """Import the fixture generator as a module.

    It has no import-time side effects (`main()` is guarded), so importing
    it gives the test the very same reference forward pass the fixture was
    generated with — no second implementation to drift.
    """
    spec = importlib.util.spec_from_file_location("gen_discrete_policy_fixture", SCRIPT_PATH)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _fixture() -> dict[str, Any]:
    if not FIXTURE_PATH.exists():
        pytest.skip(f"the discrete-policy fixture is not checked out: {FIXTURE_PATH}")
    return json.loads(FIXTURE_PATH.read_text(encoding="utf-8"))


def test_the_committed_fixture_is_a_discrete_policy() -> None:
    """A discrete export carries no `log_std` — that is the whole point."""
    fixture = _fixture()

    assert fixture["action_space"] == "discrete"
    assert fixture["action_dim"] == 5
    assert "log_std" not in fixture["layers"]


def test_the_python_forward_pass_reproduces_the_committed_actions() -> None:
    """The Python half of the forward-pass contract."""
    reference = _load_reference()
    fixture = _fixture()
    layers = fixture["layers"]

    observations = fixture["observations"]
    expected = fixture["expected_actions"]
    assert len(observations) == len(expected)

    for obs, action in zip(observations, expected, strict=True):
        assert reference.forward_discrete(obs, layers) == action


def test_the_fixture_picks_more_than_one_action() -> None:
    """The fixture must discriminate.

    A forward pass that always returned the same index would satisfy a
    fixture whose expected actions are all identical — so the committed
    expectations have to cover several actions.
    """
    fixture = _fixture()

    assert len(set(fixture["expected_actions"])) > 1


def test_the_committed_logits_are_unambiguous() -> None:
    """The top-2 margin must be wide enough to survive float32 vs float64.

    SB3 computes in float32, the exported weights and the TypeScript
    forward pass work in float64. A margin below ~1e-3 would make the
    fixture a coin flip.
    """
    reference = _load_reference()
    fixture = _fixture()
    layers = fixture["layers"]

    for obs in fixture["observations"]:
        logits = reference.forward_logits(obs, layers)
        ordered = sorted(logits, reverse=True)
        assert ordered[0] - ordered[1] > 1e-3
