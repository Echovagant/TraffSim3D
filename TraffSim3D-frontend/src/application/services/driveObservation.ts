// src/application/services/driveObservation.ts
//
// The browser side of the cooperative-driving agent's observation.
//
// Python's `DriveCore._observation` (`app/apps/rl/drive_core.py`) is the
// **authoritative** definition. This module rebuilds the *same 23
// numbers* from the browser's live state, so the trained policy reads
// the input it was trained on.
//
// The repository already knows what happens when this goes subtly
// wrong: the signal policy's phase clock (idx 5) once ran 0.52..1.0
// where Python ran 0..1 — every test stayed green (the cross-language
// contract compares the *schema*), and the only symptom was "the
// trained policy behaves oddly in the browser". The observation
// fixture (`drive-observation-fixture.json`, generated by
// `gen_drive_observation_fixture.py`) exists so THIS builder cannot
// drift like that: `driveObservationParity.spec.ts` replays the pinned
// scene states through this function and requires every element to
// match Python to 1e-9 — the repository's measured libm noise floor
// (ADR-009), not a slack.
//
// ---------------------------------------------------------------------------
// The observation, index by index (per agent)
// ---------------------------------------------------------------------------
//
//   [0]      own speed / 16.67
//   [1]      own distance to the conflict point / 100, clamped to [0, 1]
//   [2]      own arrival time — distance / max(speed, 0.5) — / 20, clamped
//   [3]      own bearing TO the conflict point (from the vehicle's
//            heading), wrapped to (-pi, pi], / pi
//   [4]      own route progress (handed in by the caller)
//   [5]      inside the arrival tolerance (2 m) — 1/0
//   [6]      how many of the others arrive before I do / their count
//   [7]      the earliest such difference, / 10, clamped
//   [8..22]  the three nearest others, five numbers each:
//            present (1/0), their offset FROM THE CONFLICT POINT in my
//            frame (x, z) / 50, their speed / 16.67, their arrival
//            time minus mine / 10, clamped
//
// Four details are where the two sides could disagree:
//
// 1. **The arrival time is not an ETA.** It is distance divided by
//    speed with the speed floored at **0.5** — a standing car gets 0.5,
//    not 0 and not infinity. The floor is what makes a stopped car's
//    arrival "very late but finite", and both sides must floor alike.
// 2. **The bearing points from the vehicle to the conflict point**
//    (atan2 of conflict − vehicle), not the other way. The generator's
//    reference once computed the opposite vector and disagreed by
//    exactly pi.
// 3. **The angle wrap is CPython's float `%`.** Python's `%` on a
//    negative dividend returns a non-negative result; JavaScript's
//    returns the dividend's sign. The wrap below adds the modulus back
//    when the remainder is negative, which is CPython's semantics.
// 4. **The others are ranked by distance to the SELF vehicle** (not to
//    the conflict point), nearest first, and the "arrives earlier"
//    count (idx 6/7) runs over **all** of them — not just the nearest
//    three that get slots.

/** The observation dimension of one cooperative driver — Python's `OBS_DIM_DRIVE`. */
export const DRIVE_OBS_DIM = 23

/** The speed the normalisation divides by (m/s) — Python's `SPEED_LIMIT_DRIVE`. */
export const DRIVE_SPEED_LIMIT = 16.67

/** The arrival tolerance (m): inside it, idx 5 reports "in the box". */
export const DRIVE_ARRIVAL_TOLERANCE_M = 2.0

/** How many of the nearest others get a slot. */
export const DRIVE_NEAREST_OTHERS = 3

/** The ego state the observation is built from. */
export interface DriveObservationSelf {
  x: number
  z: number
  /** Travel heading, radians (world XZ, math convention). */
  heading: number
  speed: number
  /** Progress along the route, in [0, 1] — computed by the caller. */
  routeProgress: number
}

/** One other vehicle the observation sees. */
export interface DriveObservationOther {
  x: number
  z: number
  speed: number
}

export interface DriveObservationInput {
  /** The junction the agents are negotiating (world coordinates). */
  conflictPoint: { x: number; z: number }
  self: DriveObservationSelf
  /** Every other vehicle in the scenario (the builder ranks them). */
  others: readonly DriveObservationOther[]
}

/**
 * Wrap an angle into `(-pi, pi]` the way CPython's float `%` does.
 *
 * Python's `%` on a negative dividend returns a non-negative result;
 * JavaScript's keeps the dividend's sign. Adding the modulus back when
 * the remainder is negative reproduces CPython exactly (a last-bit
 * difference near the boundary is what the 1e-9 parity floor absorbs).
 */
const wrapAngle = (angle: number): number => {
  const wrapped = (angle + Math.PI) % (2 * Math.PI)
  return (wrapped < 0 ? wrapped + 2 * Math.PI : wrapped) - Math.PI
}

/** The arrival-time proxy: distance over speed, the speed floored at 0.5. */
const arrivalTime = (
  x: number,
  z: number,
  speed: number,
  conflictPoint: DriveObservationInput['conflictPoint'],
): number => {
  const distance = Math.hypot(x - conflictPoint.x, z - conflictPoint.z)
  return distance / Math.max(speed, 0.5)
}

/**
 * The 23-dim observation for one driver — the browser's twin of
 * Python's `DriveCore._observation`.
 *
 * Pure by rule: no Pinia, no Three.js — the callers hand in poses.
 */
export const buildDriveObservation = (input: DriveObservationInput): number[] => {
  const obs: number[] = new Array(DRIVE_OBS_DIM).fill(0)
  const { conflictPoint, self } = input

  const ownDistance = Math.hypot(self.x - conflictPoint.x, self.z - conflictPoint.z)
  const ownArrival = arrivalTime(self.x, self.z, self.speed, conflictPoint)

  obs[0] = self.speed / DRIVE_SPEED_LIMIT
  obs[1] = Math.min(ownDistance / 100.0, 1.0)
  obs[2] = Math.max(-1.0, Math.min(1.0, ownArrival / 20.0))

  // idx 3 — the bearing TO the conflict point, from the vehicle. See
  // the module header: the vector's direction is the one that flipped
  // in the generator's reference, and a flipped bearing disagrees by
  // exactly pi.
  const bearing = wrapAngle(
    Math.atan2(conflictPoint.z - self.z, conflictPoint.x - self.x) - self.heading,
  )
  obs[3] = bearing / Math.PI
  obs[4] = self.routeProgress

  const others = [...input.others].sort(
    (a, b) => Math.hypot(a.x - self.x, a.z - self.z) - Math.hypot(b.x - self.x, b.z - self.z),
  )

  let earlier = 0
  let earliestDelta = 0.0
  for (const other of others) {
    const delta = arrivalTime(other.x, other.z, other.speed, conflictPoint) - ownArrival
    if (delta < 0) {
      earlier += 1
      earliestDelta = Math.min(earliestDelta, delta)
    }
  }
  obs[5] = ownDistance <= DRIVE_ARRIVAL_TOLERANCE_M ? 1.0 : 0.0
  obs[6] = earlier / Math.max(1, others.length)
  obs[7] = Math.max(-1.0, Math.min(1.0, earliestDelta / 10.0))

  const cosH = Math.cos(-self.heading)
  const sinH = Math.sin(-self.heading)
  for (let slot = 0; slot < DRIVE_NEAREST_OTHERS; slot += 1) {
    const other = others[slot]
    if (!other) continue // the slot stays zero — no vehicle to see
    const base = 8 + slot * 5
    // The other's offset from the CONFLICT POINT, in the ego's frame:
    // "which side of the junction is that car coming from".
    const dx = other.x - conflictPoint.x
    const dz = other.z - conflictPoint.z
    obs[base] = 1.0
    obs[base + 1] = (dx * cosH - dz * sinH) / 50.0
    obs[base + 2] = (dx * sinH + dz * cosH) / 50.0
    obs[base + 3] = other.speed / DRIVE_SPEED_LIMIT
    obs[base + 4] = Math.max(
      -1.0,
      Math.min(
        1.0,
        (arrivalTime(other.x, other.z, other.speed, conflictPoint) - ownArrival) / 10.0,
      ),
    )
  }

  return obs
}
