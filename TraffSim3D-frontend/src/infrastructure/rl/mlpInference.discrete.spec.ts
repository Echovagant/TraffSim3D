// src/infrastructure/rl/mlpInference.discrete.spec.ts
//
// The discrete forward-pass contract.
//
// The browser can only run a **continuous** 2-dim action policy today, but
// a traffic-signal agent has a **discrete 5-way** action. SB3's
// `CategoricalPolicy` produces action *logits* and has no `log_std`, so
// the forward pass is: the same layer layout as the continuous one, then
// the **argmax** of the logits (no softmax — argmax is monotonically
// equivalent for the decision and numerically steadier).
//
// THE GATE: for the same weights and the same observations, Python and the
// browser must produce the **same action index**.
//
// The fixture is generated by the backend (it owns the training side):
//   cd TraffSim3D-backend
//   .\.venv\Scripts\python.exe scripts\gen_discrete_policy_fixture.py
// It holds a real SB3 `Discrete(5)` policy's exported weights, a list of
// observations, and the action index each observation must produce.

import { describe, it, expect } from 'vitest'
import fixture from './fixtures/discrete-policy-fixture.json'
import { mlpForwardDiscrete } from './mlpInference'
import type { PolicyWeights } from './types'

const POLICY: PolicyWeights = {
  name: fixture.name,
  obs_dim: fixture.obs_dim,
  action_dim: fixture.action_dim,
  action_space: fixture.action_space as PolicyWeights['action_space'],
  hidden_sizes: fixture.hidden_sizes,
  layers: fixture.layers as PolicyWeights['layers'],
}

const OBSERVATIONS = fixture.observations as number[][]
const EXPECTED = fixture.expected_actions as number[]

describe('mlpForwardDiscrete — the discrete forward-pass contract', () => {
  it('uses a discrete policy that carries no Gaussian log-std', () => {
    expect(POLICY.action_space).toBe('discrete')
    expect(POLICY.action_dim).toBe(5)
    // A `CategoricalPolicy` has no `log_std` — the export omits the key.
    expect(POLICY.layers.log_std).toBeUndefined()
  })

  it('reproduces the Python action for every committed observation', () => {
    expect(OBSERVATIONS).toHaveLength(EXPECTED.length)
    OBSERVATIONS.forEach((obs, i) => {
      expect(mlpForwardDiscrete(obs, POLICY)).toBe(EXPECTED[i])
    })
  })

  it('picks different actions for different observations', () => {
    // Otherwise the fixture would also be satisfied by a forward pass that
    // always returned the same index.
    expect(new Set(EXPECTED).size).toBeGreaterThan(1)
  })

  it('rejects an observation whose dimension differs from the policy weights', () => {
    const mismatched = [...(OBSERVATIONS[0] as number[]), 0.0]
    expect(() => mlpForwardDiscrete(mismatched, POLICY)).toThrow(
      /obs dim mismatch: got \d+, weights expect \d+/,
    )
  })

  it('is deterministic (the same observation gives the same action)', () => {
    const obs = OBSERVATIONS[0] as number[]
    expect(mlpForwardDiscrete(obs, POLICY)).toBe(mlpForwardDiscrete(obs, POLICY))
  })

  it('returns an index inside the action space', () => {
    for (const obs of OBSERVATIONS) {
      const action = mlpForwardDiscrete(obs, POLICY)
      expect(Number.isInteger(action)).toBe(true)
      expect(action).toBeGreaterThanOrEqual(0)
      expect(action).toBeLessThan(POLICY.action_dim)
    }
  })
})
